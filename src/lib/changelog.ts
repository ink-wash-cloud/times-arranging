/** 简易版本号比较：a > b 返回正数 */
export function compareVersion(a: string, b: string): number {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const x = pa[i] || 0, y = pb[i] || 0;
    if (x !== y) return x - y;
  }
  return 0;
}

/** 比 seen 新的那些版本（新的排前面）。seen 为空表示第一次装，返回空数组。 */
export function notesSince(seen: string): ReleaseNote[] {
  if (!seen) return [];
  return CHANGELOG.filter((r) => compareVersion(r.v, seen) > 0);
}
