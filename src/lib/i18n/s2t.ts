const CHAR = new Map<string, string>();
for (const p of PAIRS) {
  if (p.length !== 2) throw new Error('s2t: bad pair ' + p);
  CHAR.set(p.charAt(0), p.charAt(1));
}
// 长词优先
const PHRASES_SORTED = PHRASES.slice().sort((x, y) => y[0].length - x[0].length);

const cache = new Map<string, string>();
const CJK = /[\u4e00-\u9fff]/;

/** 把一段简体中文转成繁体中文（结果按入参缓存，界面切来切去不会重复算） */
export function toHant(text: string): string {
  if (!text || !CJK.test(text)) return text;
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  let out = '';
  let i = 0;
  while (i < text.length) {
    let matched = '';
    for (let k = 0; k < PHRASES_SORTED.length; k++) {
      const s = PHRASES_SORTED[k][0];
      if (s.length <= text.length - i && text.startsWith(s, i)) {
        matched = PHRASES_SORTED[k][1];
        i += s.length;
        break;
      }
    }
    if (matched) { out += matched; continue; }
    const ch = text.charAt(i);
    out += CHAR.get(ch) || ch;
    i += 1;
  }
  cache.set(text, out);
  return out;
}

/** 繁体表里覆盖了多少个字（测试用：确认表没被误删） */
export function hantCoverage(): number {
  return CHAR.size;
}
